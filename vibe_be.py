_BY_ORIG_NAME: Dict[str, Dict[str, Any]] = {
    v["orig_name"]: v for v in VIBES_BE.values()
}
_BY_ORIG_NAME.setdefault("THE WHITE WALKER", VIBES_BE[15])


def get_be_vibe(vibe_name: str) -> Tuple[str, str]:
    """Returns (name, quote) for the given BE vibe according to active pick ('orig' or 'a'..'g')."""
    entry = _BY_ORIG_NAME.get(vibe_name)
    if not entry:
        return vibe_name, ""
    pick = entry.get("pick", "orig").lower()
    if pick == "orig" or pick not in entry:
        return entry["orig_name"], entry["orig_quote"]
    t_name, t_quote = entry[pick]
    return t_name, t_quote
